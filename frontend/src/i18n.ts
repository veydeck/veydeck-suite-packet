let currentLocale: Locale = "zh-CN";
const listeners = new Set<() => void>();

export function setLocale(locale: string) {
  const nextLocale: Locale = locale.startsWith("en") ? "en-US" : "zh-CN";
  if (currentLocale === nextLocale) return;
  currentLocale = nextLocale;
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function snapshot() {
  return currentLocale;
}

export function useLocale() {
  const locale = useSyncExternalStore(subscribe, snapshot, snapshot);
  const dict = dictionaries[locale];
  const t = (template: string, values?: Record<string, string | number>) => {
    if (!values) return template;
    return Object.entries(values).reduce(
      (message, [key, value]) => message.replaceAll(`{${key}}`, String(value)),
      template,
    );
  };
  return { locale, dict, t };
}
